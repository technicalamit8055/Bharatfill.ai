/**
 * Operator-taught mappings and the contributions they can become.
 * Master spec §14.3 (priority 2 org override, priority 6 manual mapping), §9.6 (anonymised
 * field metadata only); docs/FORM_ENGINE.md §6c.
 *
 * The flow: an operator maps a box the engine did not recognise. That is saved as their own
 * centre's override straight away. Optionally — ticked by default — the *portal's* side of it
 * (the label the portal printed, the box's name/id, which customer field it means) is sent to
 * Bharatfill staff for review. Once approved it becomes an adapter field that every centre gets.
 *
 * What a contribution may carry is decided here, not at the call sites. It never carries a
 * customer value, and every piece of page text in it goes through `sanitiseContributionText`,
 * because a portal can print anything beside a box — including the applicant's own details on a
 * pre-filled page.
 */

import { z } from 'zod';
import { DICTIONARY_BY_FIELD } from './dictionary';
import {
  adapterFieldMatchScore,
  normaliseForMatch,
  type AdapterField,
  type PortalAdapter,
} from './adapters';
import { classifyField } from './safety';
import type { DetectedField, PageContext, SafetyClass } from './types';

const EMAIL = /[^\s@]+@[^\s@]+\.[^\s@]+/;
/** PAN shape: five letters, four digits, one letter. */
const PAN = /\b[A-Z]{5}\d{4}[A-Z]\b/i;
/** Any run of four or more digits, allowing the spaces and dashes IDs are printed with. */
const LONG_NUMBER = /\d(?:[\s-]?\d){3,}/g;

export const CONTRIBUTION_TEXT_MAX = 200;

/**
 * Page text made safe to leave the centre, or `null` when it cannot be.
 *
 * Text with an email or a PAN-shaped token is dropped whole rather than masked: what sits around
 * such a token is likely to be the person it belongs to. Long digit runs (phone, Aadhaar,
 * application numbers) are masked to `#`, since "Year of passing (e.g. 2015)" is still a useful
 * label once the year is gone.
 */
export function sanitiseContributionText(text: string | null | undefined): string | null {
  if (typeof text !== 'string') return null;
  const collapsed = text.replace(/\s+/g, ' ').trim();
  if (!collapsed) return null;
  if (EMAIL.test(collapsed) || PAN.test(collapsed)) return null;
  const masked = collapsed.replace(LONG_NUMBER, '#').slice(0, CONTRIBUTION_TEXT_MAX).trim();
  return masked.length > 0 ? masked : null;
}

/**
 * Control names generated by a front-end framework, which mean nothing outside one render of one
 * page: SSC's Angular forms number theirs (`ctrl_12`), Material numbers its inputs.
 */
const GENERATED_ATTRIBUTE =
  /^(?:ctrl|ctl|control|field|fld|input|inp|txt|text|textbox|select|ddl|dropdown|mat-input|mat-select|mat-radio|cdk|ng|el|f|q|id|item|elem|element|form|formcontrol)[-_.:]?\d+$/i;

/**
 * A `name` or `id` attribute worth keeping, or `null`.
 *
 * Kept only when it reads like a developer's word for the field: an attribute that is mostly
 * digits is a row id or a session token, and a generated one would match an unrelated box on
 * the next page.
 */
export function sanitiseContributionAttribute(value: string | null | undefined): string | null {
  if (typeof value !== 'string') return null;
  const trimmed = value.trim();
  if (!trimmed || trimmed.length > 80) return null;
  if (!/^[A-Za-z][\w$.:[\]-]*$/.test(trimmed)) return null;
  if (GENERATED_ATTRIBUTE.test(trimmed)) return null;
  if (/\d{5,}/.test(trimmed)) return null;
  const letters = trimmed.replace(/[^A-Za-z]/g, '');
  if (letters.length < 4) return null;
  return trimmed;
}

/**
 * The path with anything id-like replaced by `*`, so the contribution names the form rather than
 * one applicant's page of it (`/application/48213977/edit` → `/application/*\/edit`).
 */
export function contributionPathPattern(path: string): string {
  const withoutQuery = path.split(/[?#]/)[0] ?? '';
  const segments = withoutQuery
    .split('/')
    .map((segment) => (/\d{3,}/.test(segment) || segment.length > 60 ? '*' : segment));
  const joined = segments.join('/');
  return (joined.startsWith('/') ? joined : `/${joined}`).slice(0, 300);
}

export const mappingContributionSchema = z.object({
  pageOrigin: z.string().url().max(300),
  pathPattern: z.string().max(300),
  fieldSignature: z.string().min(1).max(200),
  tagName: z.enum(['input', 'select', 'textarea']),
  inputType: z.string().max(40),
  labelText: z.string().max(CONTRIBUTION_TEXT_MAX).nullable(),
  ariaLabel: z.string().max(CONTRIBUTION_TEXT_MAX).nullable(),
  placeholder: z.string().max(CONTRIBUTION_TEXT_MAX).nullable(),
  sectionHeading: z.string().max(CONTRIBUTION_TEXT_MAX).nullable(),
  nameAttribute: z.string().max(80).nullable(),
  idAttribute: z.string().max(80).nullable(),
  customerField: z.string().regex(/^customer\./),
});

export type MappingContribution = z.infer<typeof mappingContributionSchema>;

/**
 * The shareable half of a taught mapping, or `null` when nothing would identify the box once the
 * unsafe parts are gone (then the centre keeps its override and nothing is shared).
 */
export function buildMappingContribution(
  field: Pick<
    DetectedField,
    | 'signature'
    | 'tagName'
    | 'inputType'
    | 'labelText'
    | 'ariaLabel'
    | 'placeholder'
    | 'sectionHeading'
    | 'name'
    | 'id'
  >,
  page: Pick<PageContext, 'origin' | 'path'>,
  customerField: string,
): MappingContribution | null {
  const contribution: MappingContribution = {
    pageOrigin: page.origin,
    pathPattern: contributionPathPattern(page.path),
    fieldSignature: field.signature,
    tagName: field.tagName,
    inputType: field.inputType.slice(0, 40),
    labelText: sanitiseContributionText(field.labelText),
    ariaLabel: sanitiseContributionText(field.ariaLabel),
    placeholder: sanitiseContributionText(field.placeholder),
    sectionHeading: sanitiseContributionText(field.sectionHeading),
    nameAttribute: sanitiseContributionAttribute(field.name),
    idAttribute: sanitiseContributionAttribute(field.id),
    customerField,
  };
  return contributionMatchTexts(contribution).length > 0 ? contribution : null;
}

/** Boxes that hold no customer text, so there is nothing to teach about them. */
export const UNTEACHABLE_INPUT_TYPES: ReadonlySet<string> = new Set([
  'file',
  'hidden',
  'password',
  'button',
  'submit',
  'reset',
  'image',
]);

/**
 * Why a box may not be taught, or `null` when it may.
 *
 * The same classifier the mapper runs first: a CAPTCHA, OTP, payment or submit control is never
 * filled, so it is never taught either — whatever a client sends (§14.8). Checked on the server.
 */
export function unteachableReason(
  field: Pick<
    DetectedField,
    'inputType' | 'name' | 'id' | 'placeholder' | 'labelText' | 'ariaLabel' | 'nearbyText' | 'maxLength'
  >,
): `safety_${Exclude<SafetyClass, 'normal'>}` | 'unsupported_type' | null {
  const safetyClass = classifyField({
    inputType: field.inputType,
    name: field.name,
    id: field.id,
    placeholder: field.placeholder,
    labelText: field.labelText,
    ariaLabel: field.ariaLabel,
    nearbyText: field.nearbyText,
    maxLength: field.maxLength,
  });
  if (safetyClass !== 'normal') return `safety_${safetyClass}`;
  if (UNTEACHABLE_INPUT_TYPES.has(field.inputType.toLowerCase())) return 'unsupported_type';
  return null;
}

/** The texts an approved contribution will be matched on: its own label first, then attributes. */
export function contributionMatchTexts(
  contribution: Pick<
    MappingContribution,
    'labelText' | 'ariaLabel' | 'placeholder' | 'nameAttribute' | 'idAttribute'
  >,
): string[] {
  const texts: string[] = [];
  const seen = new Set<string>();
  for (const text of [
    contribution.labelText,
    contribution.ariaLabel,
    contribution.placeholder,
    contribution.nameAttribute,
    contribution.idAttribute,
  ]) {
    if (!text) continue;
    // A masked text ("Mobile #") is fine for a reviewer to read, but would never equal the live
    // label it came from, so it is not offered as a pattern.
    if (text.includes('#')) continue;
    const normalised = normaliseForMatch(text);
    if (!normalised || seen.has(normalised)) continue;
    seen.add(normalised);
    texts.push(text);
  }
  return texts;
}

/**
 * Contributions that say the same thing: same portal, same box (by its first match text), same
 * customer field. The review queue counts distinct centres per group.
 */
export function contributionGroupKey(
  contribution: Pick<
    MappingContribution,
    | 'pageOrigin'
    | 'labelText'
    | 'ariaLabel'
    | 'placeholder'
    | 'nameAttribute'
    | 'idAttribute'
    | 'customerField'
  >,
): string {
  return [
    contribution.pageOrigin.toLowerCase(),
    contributionBoxKey(contribution),
    contribution.customerField,
  ].join('|');
}

/** Identifies the box alone, so two groups for one box with different fields can be flagged. */
export function contributionBoxKey(
  contribution: Pick<
    MappingContribution,
    'pageOrigin' | 'labelText' | 'ariaLabel' | 'placeholder' | 'nameAttribute' | 'idAttribute'
  >,
): string {
  const first = contributionMatchTexts(contribution)[0];
  return `${contribution.pageOrigin.toLowerCase()}|${first ? normaliseForMatch(first) : ''}`;
}

/**
 * The transform a taught mapping should carry: the dictionary's own for that customer field,
 * except on a native date box, which takes ISO dates and would reject 14/07/1998.
 */
export function defaultTransformFor(customerField: string, inputType: string): string | undefined {
  if (inputType.toLowerCase() === 'date') return undefined;
  return DICTIONARY_BY_FIELD.get(customerField)?.transform;
}

/** `1.2.0` → `1.2.1`. Anything unparseable restarts the patch count from the major.minor it has. */
export function bumpPatchVersion(version: string): string {
  const match = /^(\d+)\.(\d+)\.(\d+)/.exec(version.trim());
  if (!match) return '1.0.1';
  return `${match[1]}.${match[2]}.${Number(match[3]) + 1}`;
}

function slugPart(text: string): string {
  return normaliseForMatch(text)
    // Devanagari stays in the key, so a Hindi-only label still gives a readable one.
    .replace(/[^a-z0-9\p{Script=Devanagari}]+/gu, '_')
    .replace(/^_+|_+$/g, '')
    .slice(0, 50);
}

/**
 * The adapter field an approved contribution becomes.
 *
 * Always `exact` label matching (adapters.ts), always `reviewRequired`: a centre's mapping is
 * reviewed by staff once, then checked by every operator who fills with it until a human
 * verifies the adapter. The key is prefixed so it can never token-match a portal's own `name`.
 */
export function contributionToAdapterField(
  contribution: MappingContribution,
  existingKeys: ReadonlySet<string>,
): AdapterField | null {
  const patterns = contributionMatchTexts(contribution);
  if (patterns.length === 0) return null;

  const base = `crowd_${slugPart(patterns[0] ?? '') || 'field'}`;
  let key = base.slice(0, 80);
  for (let n = 2; existingKeys.has(key); n += 1) key = `${base.slice(0, 75)}_${n}`;

  const transform = defaultTransformFor(contribution.customerField, contribution.inputType);
  return {
    key,
    customerField: contribution.customerField,
    labelPatterns: patterns.slice(0, 20),
    labelMatch: 'exact',
    inputType: contribution.inputType || contribution.tagName,
    reviewRequired: true,
    origin: 'contribution',
    ...(transform ? { transform } : {}),
  };
}

export type ContributionMerge = {
  adapter: PortalAdapter;
  /** True when an earlier contributed field for the same box was replaced. */
  replaced: boolean;
};

/**
 * Adds an approved contribution to an adapter as a new field, and bumps the patch version.
 *
 * An earlier *contributed* field for the same box is replaced (the reviewer has picked a newer
 * answer). A hand-written field is never touched: if one already claims this box, the merge is
 * refused with `null`, because the contribution would be shadowing a verified mapping.
 */
export function mergeContributionIntoAdapter(
  adapter: PortalAdapter,
  contribution: MappingContribution,
): ContributionMerge | null {
  const probe = {
    signature: contribution.fieldSignature,
    name: contribution.nameAttribute,
    id: contribution.idAttribute,
    labelText: contribution.labelText,
    placeholder: contribution.placeholder,
    ariaLabel: contribution.ariaLabel,
  };

  const patterns = new Set(contributionMatchTexts(contribution).map(normaliseForMatch));
  const sameBox = (field: AdapterField) =>
    field.origin === 'contribution' &&
    (field.labelPatterns ?? []).some((pattern) => patterns.has(normaliseForMatch(pattern)));

  const remaining = adapter.fields.filter((field) => !sameBox(field));
  const replaced = remaining.length !== adapter.fields.length;

  // A hand-written field that already claims this box wins; the contribution is redundant or
  // wrong, and either way it must not shadow a verified mapping.
  for (const field of remaining) {
    if (field.origin === 'contribution') continue;
    if (handWrittenClaims(field, probe)) return null;
  }

  const next = contributionToAdapterField(
    contribution,
    new Set(remaining.map((field) => field.key)),
  );
  if (!next) return null;

  return {
    adapter: {
      ...adapter,
      version: bumpPatchVersion(adapter.version),
      fields: [...remaining, next],
    },
    replaced,
  };
}

function handWrittenClaims(
  field: AdapterField,
  probe: {
    signature: string;
    name: string | null;
    id: string | null;
    labelText: string | null;
    placeholder: string | null;
    ariaLabel: string | null;
  },
): boolean {
  // Re-uses the live matcher so "claims" means exactly what it means on the portal.
  return adapterFieldMatchScore(field, probe) !== null;
}

export type StoredContribution = {
  id: string;
  organizationId: string;
  createdAt: string;
  contribution: MappingContribution;
};

export type ContributionGroup = {
  key: string;
  /** The most recent contribution, used as the representative for display and approval. */
  latest: MappingContribution;
  ids: string[];
  /** Distinct centres that taught this exact answer. The number a reviewer should trust. */
  centres: number;
  firstSeen: string;
  lastSeen: string;
  /** Other customer fields centres taught for the same box, with their centre counts. */
  conflicts: { customerField: string; centres: number }[];
};

/**
 * Review-queue groups, most-agreed first. A box two centres disagree on is listed under each
 * answer, and each lists the other as a conflict, so neither can be approved without seeing both.
 */
export function groupContributions(rows: readonly StoredContribution[]): ContributionGroup[] {
  const groups = new Map<
    string,
    { rows: StoredContribution[]; organizations: Set<string>; box: string }
  >();
  for (const row of rows) {
    const key = contributionGroupKey(row.contribution);
    const entry = groups.get(key) ?? {
      rows: [],
      organizations: new Set<string>(),
      box: contributionBoxKey(row.contribution),
    };
    entry.rows.push(row);
    entry.organizations.add(row.organizationId);
    groups.set(key, entry);
  }

  const result: ContributionGroup[] = [];
  for (const [key, entry] of groups) {
    const sorted = [...entry.rows].sort((a, b) => b.createdAt.localeCompare(a.createdAt));
    const latest = sorted[0];
    if (!latest) continue;
    const conflicts = [...groups.entries()]
      .filter(([otherKey, other]) => otherKey !== key && other.box === entry.box)
      .map(([, other]) => ({
        customerField: other.rows[0]?.contribution.customerField ?? '',
        centres: other.organizations.size,
      }))
      .sort((a, b) => b.centres - a.centres);
    result.push({
      key,
      latest: latest.contribution,
      ids: sorted.map((row) => row.id),
      centres: entry.organizations.size,
      firstSeen: sorted[sorted.length - 1]?.createdAt ?? latest.createdAt,
      lastSeen: latest.createdAt,
      conflicts,
    });
  }

  return result.sort(
    (a, b) => b.centres - a.centres || b.lastSeen.localeCompare(a.lastSeen),
  );
}

/** A new adapter for a portal nobody has written one for yet, seeded by its first contribution. */
export function newContributedAdapter(input: {
  origin: string;
  portalName: string;
  formName: string;
  region?: string;
}): PortalAdapter {
  const host = new URL(input.origin).hostname.replace(/^www\./, '');
  return {
    id: `crowd-${host}`,
    slug: `crowd-${slugPart(host).replace(/_/g, '-')}`.slice(0, 80),
    portalName: input.portalName.slice(0, 160),
    formName: input.formName.slice(0, 160),
    ...(input.region ? { region: input.region.slice(0, 120) } : {}),
    urlPatterns: [`${input.origin}/**`],
    version: '0.1.0',
    status: 'testing',
    fields: [],
    documentRequirements: [],
    notes: 'Built from operator contributions reviewed in the admin panel. Every field is reviewed by the operator before it fills.',
  };
}
