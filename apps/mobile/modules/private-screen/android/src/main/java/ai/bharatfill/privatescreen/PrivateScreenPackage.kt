package ai.bharatfill.privatescreen

import android.app.Activity
import android.content.Context
import android.os.Build
import android.os.Bundle
import expo.modules.core.interfaces.Package
import expo.modules.core.interfaces.ReactActivityLifecycleListener

/**
 * Keeps the app's screen out of Android's recent-apps preview (Android 13+), so an open Aadhaar
 * or marksheet never shows in the app switcher or a screenshot of it.
 *
 * Only the preview is hidden: the citizen can still take screenshots inside the app (they share
 * documents that way), which FLAG_SECURE would block. Android 12 and older have no preview-only
 * switch, so those phones keep the system's preview.
 *
 * A lifecycle listener in a local Expo module rather than an edit to MainActivity, because the
 * `android/` project is regenerated by `expo prebuild` and would lose the edit.
 */
class PrivateScreenPackage : Package {
  override fun createReactActivityLifecycleListeners(
    activityContext: Context,
  ): List<ReactActivityLifecycleListener> =
    listOf(
      object : ReactActivityLifecycleListener {
        override fun onCreate(activity: Activity, savedInstanceState: Bundle?) {
          if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.TIRAMISU) {
            activity.setRecentsScreenshotEnabled(false)
          }
        }
      },
    )
}
